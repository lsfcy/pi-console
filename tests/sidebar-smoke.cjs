function menuGroups(template) {
  const groups = [[]];
  for (const item of template) {
    if (item.type === 'separator') { assert(groups.at(-1).length, 'no leading or adjacent separators'); groups.push([]); }
    else {
      assert(item.icon && !item.icon.isEmpty(), 'native menu actions have a visible icon: ' + item.label);
      assert.deepEqual(item.icon.getSize(),{width:16,height:16},'menu icons use native logical size with a 2x bitmap');
      assert(item.icon.isTemplateImage(),'menu icons adapt to light/dark and disabled state');
      groups.at(-1).push(item.label);
    }
  }
  assert(groups.at(-1).length, 'no trailing separator');
  return groups;
}
