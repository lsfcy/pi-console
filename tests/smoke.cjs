function spawnPty(file, args, options) {
  if (!(args[1] || '').startsWith('exec pi update')) {
    const proc = realSpawn(file, args, options); allPids.push(proc.pid);
    if ((args[1] || '').startsWith('exec pi --extension')) {
      const write = proc.write.bind(proc);
      proc.write = data => { piInputs.push(data); return write(data); };
    }
    return proc;
  }
  updateExecutions++;
  let data, exit;
  const timer = setTimeout(() => { data?.('SIMULATED_UPDATE_ONLY: no installed Pi files were changed\r\n'); exit?.({ exitCode: args[1].includes('--all') ? 1 : 0 }); }, 250);
  return { pid: 6000000, onData(fn) { data = fn; }, onExit(fn) { exit = fn; }, write() {}, resize() {}, pause() {}, resume() {},
    kill() { clearTimeout(timer); exit?.({ exitCode: 143, signal: 15 }); } };
}
